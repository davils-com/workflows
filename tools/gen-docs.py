#!/usr/bin/env python3
"""Generates the reference topics of the documentation from the workflows, actions and defaults.

Writes docs/topics/reference/*.md: one topic per reusable workflow (inputs, secrets, outputs),
one for the composite actions and one for every option of .github/davils-ci.yaml. Run
tools/gen-docs.sh; self-lint fails when the committed topics are stale.

Reads a JSON document on stdin: {"workflows": {file: workflow}, "actions": {dir: action},
"defaults": {...}, "schema": {...}} and writes the topics into the directory given as argument.
"""

import json
import os
import sys

TITLES = {
    "pipeline.yml": "pipeline.yml",
    "dart-ci.yml": "dart-ci.yml",
    "flutter-ci.yml": "flutter-ci.yml",
    "inspectra.yml": "inspectra.yml",
    "writerside.yml": "writerside.yml",
    "dartdoc.yml": "dartdoc.yml",
    "pages.yml": "pages.yml",
    "flutter-build.yml": "flutter-build.yml",
    "dart-compile.yml": "dart-compile.yml",
    "pub-publish.yml": "pub-publish.yml",
    "github-release.yml": "github-release.yml",
    "release-tag.yml": "release-tag.yml",
    "release-please.yml": "release-please.yml",
    "pr-lint.yml": "pr-lint.yml",
    "test-report.yml": "test-report.yml",
}

HEADER = "<!-- Generated by tools/gen-docs.sh from the workflows, actions and defaults. Do not edit by hand. -->\n\n"


def cell(value):
    text = "" if value is None else str(value)
    return text.replace("|", "\\|").replace("\n", " ").strip()


def default(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    text = str(value)
    if text == "":
        return "empty"
    text = text.rstrip("\n")
    return "`" + text.replace("|", "\\|").replace("\n", "\\n") + "`"


def header_comment(path):
    """The leading comment block of a workflow file, without the # marks."""
    lines = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if line.startswith("name:") or not line.strip():
                if lines and not line.strip():
                    lines.append("")
                continue
            if not line.startswith("#"):
                break
            lines.append(line[1:].rstrip("\n")[1:] if line.startswith("# ") else line[1:].rstrip("\n"))
    return "\n".join(lines).strip()


def workflow_topic(file, workflow, root):
    call = (workflow.get("on") or {}).get("workflow_call") or {}
    name = workflow.get("name", file)
    out = [HEADER, f"# {TITLES.get(file, file)}\n\n"]
    out.append(f"<link-summary>Inputs, secrets and outputs of the reusable workflow {name}.</link-summary>\n\n")
    comment = header_comment(os.path.join(root, ".github", "workflows", file))
    if comment:
        out.append("```text\n" + comment + "\n```\n\n")
    out.append("```yaml\n")
    out.append("jobs:\n")
    out.append(f"  {file.removesuffix('.yml')}:\n")
    out.append(f"    uses: davils-com/workflows/.github/workflows/{file}@v1\n")
    out.append("```\n\n")
    inputs = call.get("inputs") or {}
    if inputs:
        out.append("## Inputs\n\n| Input | Type | Default | Description |\n|---|---|---|---|\n")
        for key, spec in inputs.items():
            out.append(f"| `{key}` | {spec.get('type', '')} | {default(spec.get('default'))} | {cell(spec.get('description'))} |\n")
        out.append("\n")
    secrets = call.get("secrets") or {}
    if secrets:
        out.append("## Secrets\n\nAll secrets are optional.\n\n")
        out.append("".join(f"- `{key}`\n" for key in secrets))
        out.append("\n")
    outputs = call.get("outputs") or {}
    if outputs:
        out.append("## Outputs\n\n| Output | Description |\n|---|---|\n")
        for key, spec in outputs.items():
            out.append(f"| `{key}` | {cell(spec.get('description'))} |\n")
        out.append("\n")
    permissions = {}
    for job in (workflow.get("jobs") or {}).values():
        for scope, level in (job.get("permissions") or {}).items():
            if level == "write" or permissions.get(scope) != "write":
                permissions[scope] = level
    if permissions:
        out.append("## Permissions the caller grants\n\n")
        out.append("".join(f"- `{scope}: {level}`\n" for scope, level in sorted(permissions.items())))
        out.append("\n")
    return "".join(out).rstrip("\n") + "\n"


def actions_topic(actions):
    out = [HEADER, "# Composite actions\n\n"]
    out.append("<link-summary>Inputs and outputs of every composite action of davils-com/workflows.</link-summary>\n\n")
    out.append("The reusable workflows are built from these actions. Custom workflows can use them directly:\n\n")
    out.append("```yaml\n- uses: davils-com/workflows/actions/setup-dart-env@v1\n```\n\n")
    for directory in sorted(actions):
        action = actions[directory]
        out.append(f"## {directory}\n\n{cell(action.get('description'))}\n\n")
        inputs = action.get("inputs") or {}
        if inputs:
            out.append("| Input | Default | Description |\n|---|---|---|\n")
            for key, spec in inputs.items():
                required = " (required)" if spec.get("required") else ""
                out.append(f"| `{key}`{required} | {default(spec.get('default'))} | {cell(spec.get('description'))} |\n")
            out.append("\n")
        outputs = action.get("outputs") or {}
        if outputs:
            out.append("| Output | Description |\n|---|---|\n")
            for key, spec in outputs.items():
                out.append(f"| `{key}` | {cell(spec.get('description'))} |\n")
            out.append("\n")
    return "".join(out).rstrip("\n") + "\n"


def flatten(schema, prefix=""):
    rows = []
    for key, spec in (schema.get("properties") or {}).items():
        path = f"{prefix}.{key}" if prefix else key
        if spec.get("type") == "object" and "properties" in spec:
            rows.extend(flatten(spec, path))
            continue
        allowed = ""
        if "enum" in spec:
            allowed = ", ".join(f"`{json.dumps(v) if not isinstance(v, str) else v}`" for v in spec["enum"])
        elif spec.get("$ref") == "#/$defs/toggle":
            allowed = "`true`, `false`, `auto`"
        elif spec.get("$ref") == "#/$defs/when":
            allowed = "events, branches, paths"
        elif spec.get("type") == "array":
            items = spec.get("items") or {}
            allowed = "list of " + (", ".join(f"`{v}`" for v in items["enum"]) if "enum" in items else items.get("type", "values"))
        else:
            allowed = spec.get("type", "")
        if "const" in spec:
            rows.append((path, spec["const"], f"`{spec['const']}`", spec.get("description", "")))
            continue
        rows.append((path, spec.get("default"), allowed, spec.get("description", "")))
    return rows


def config_topic(defaults_yaml, schema):
    out = [HEADER, "# Configuration reference\n\n"]
    out.append("<link-summary>Every option of .github/davils-ci.yaml with its default.</link-summary>\n\n")
    out.append("Every option with its default, read from `actions/resolve-config/defaults.yaml`. A repository only writes what differs; ")
    out.append("lists replace the default, mappings merge key by key. The JSON schema is `schemas/davils-ci.schema.json`.\n\n")
    out.append("## Options\n\n| Option | Default | Values |\n|---|---|---|\n")
    for path, value, allowed, _ in flatten(schema):
        if path.endswith(".when"):
            value = None
        shown = default(json.dumps(value) if isinstance(value, list) else value) if value is not None else ""
        out.append(f"| `{path}` | {shown} | {cell(allowed)} |\n")
    out.append("\n## The defaults file\n\n```yaml\n" + defaults_yaml.rstrip("\n") + "\n```\n")
    return "".join(out)


def main():
    data = json.load(sys.stdin)
    target = sys.argv[1]
    root = sys.argv[2]
    os.makedirs(target, exist_ok=True)
    topics = {}
    for file, workflow in sorted(data["workflows"].items()):
        if file.startswith("self-"):
            continue
        name = "Workflow-" + file.removesuffix(".yml") + ".md"
        topics[name] = workflow_topic(file, workflow, root)
    topics["Actions.md"] = actions_topic(data["actions"])
    topics["Configuration-Reference.md"] = config_topic(data["defaults_yaml"], data["schema"])
    for name, text in topics.items():
        with open(os.path.join(target, name), "w", encoding="utf-8") as handle:
            handle.write(text)
    print("\n".join(sorted(topics)))


if __name__ == "__main__":
    main()
